type Db = Awaited<ReturnType<typeof setup>>;
type Listing = { gradeLevel: string; auto: string[]; chapters: { key: string; chapter: string; ownGrade: boolean; questionCount: number }[] };

function helpers(db: Db) {
  const as = (role: string) => db.exec(`reset role; select set_config('request.jwt.claim.sub','${user}',false); set role ${role};`);
  const scalar = async (sql: string, params: unknown[] = []) => (await db.query<{ value: string }>(sql, params)).rows[0]?.value;
  const startArena = async (mode: string | null, keys: string[] | null) => {
    await as("authenticated");
    return (await scalar("select start_raid_arena_run($1,$2,$3,$4) as value", [pet, mist, mode, keys]))!;
  };
  const used = async () => {
    await as("postgres");
    return Number(await scalar("select count(*)::text as value from raid_tickets where consumed_at is not null"));
  };
  const closeRuns = async () => {
    await as("postgres");
    await db.exec("update raid_runs set status='completed',phase='done' where status='in_progress'");
  };
  // Create the v4 state exactly as readCardBattle does, then return its revision.
  const initState = async (run: string) => {
    await as("service_role");
    const stats = (await db.query<{ stat_snapshot: Stats }>("select stat_snapshot from raid_runs where id=$1", [run])).rows[0].stat_snapshot;
    const state = createChapterBattle("ridge_mist", stats, () => 0.4);
    await db.query("select commit_raid_card_turn($1,$2,0,$3)", [run, user, JSON.stringify(state)]);
    return state;
  };
  const pick = async (run: string, revision: number, card = "strike") => {
    await as("service_role");
    await db.query("select pick_raid_move($1,$2,$3,$4)", [run, user, revision, card]);
  };
  const picked = async (run: string, revision: number) => {
    await as("postgres");
    return (await db.query<{ card_id: string; question_id: number; category: string; subject: string }>(
      "select card_id,question_id,question->>'category' as category,question->>'subject' as subject from raid_card_questions where run_id=$1 and revision=$2",
      [run, revision],
    )).rows;
  };
  // Advance the revision directly so several picks can be tested without playing out a turn.
  const bump = async (run: string) => {
    await as("postgres");
    return Number(await scalar("update raid_card_battles set revision=revision+1 where run_id=$1 returning revision::text as value", [run]));
  };
  return { as, scalar, startArena, used, closeRuns, initState, pick, picked, bump };
}

const A = key("math", "A"), B = key("math", "B"), C = key("science", "C"), D = key("science", "D");

test("arena: pool, listing and auto chapters", async () => {
  const db = await setup();
  const h = helpers(db);
  try {
    await h.as("postgres");
    const pool = (await db.query<{ chapter_key: string; question_count: number; grade_level: string }>("select * from _raid_chapter_pool('junior')")).rows;
    assert.deepEqual(pool.map((p) => p.chapter_key).sort(), [A, B, C, D].sort(), "fewer than 8 questions stays out");
    assert.equal(pool.find((p) => p.chapter_key === C)?.question_count, 8);
    assert.equal(pool.find((p) => p.chapter_key === C)?.grade_level, "ม.2");

    // The same key format draw_raid_chapter_hand writes to raid_chapter_offers.
    await h.as("authenticated");
    const legacy = (await h.scalar("select start_raid_chapter_run($1,$2) as value", [pet, mist]))!;
    await h.initState(legacy);
    await db.query("select draw_raid_chapter_hand($1,$2,1)", [legacy, user]);
    const offered = (await db.query<{ chapter_key: string }>("select chapter_key from raid_chapter_offers where run_id=$1", [legacy])).rows;
    assert.ok(offered.length > 0);
    for (const offer of offered) assert.ok([A, B, C, D, key("math", "Small")].includes(offer.chapter_key), offer.chapter_key);
    await h.closeRuns();

    const list = async () => {
      await h.as("authenticated");
      return (await db.query<{ value: Listing }>("select list_raid_chapters() as value")).rows[0].value;
    };
    let listing = await list();
    assert.equal(listing.gradeLevel, "ม.2");
    assert.equal(listing.chapters[0].chapter, "C", "own grade first");
    assert.equal(listing.chapters[0].ownGrade, true);
    assert.equal(listing.chapters.length, 4);
    assert.equal(listing.auto.length, 3);

    await h.as("postgres");
    const attempts = (chapter: string, source: string | null, n: number, age = "0 days") => db.query(
      `insert into quiz_attempts(user_id,question_id,source,created_at)
       select $1,(select min(id) from questions where chapter=$2),$3,now()-$5::interval from generate_series(1,$4::int)`,
      [user, chapter, source, n, age],
    );
    await attempts("D", "raid_boss", 50);
    await attempts("D", "pvp", 50);
    await attempts("D", null, 50, "31 days");
    await attempts("B", null, 3);
    await attempts("A", "topic_select", 2);
    for (let i = 0; i < 5; i++) {
      listing = await list();
      assert.equal(listing.auto[0], B, "most practised first");
      assert.equal(listing.auto[1], A, "topic_select counts");
      assert.ok(pool.some((p) => p.chapter_key === listing.auto[2]));
    }
  } finally { await db.close(); }
});

test("arena: start_raid_arena_run validates before using a key", async () => {
  const db = await setup();
  const h = helpers(db);
  try {
    const run = await h.startArena("manual", [A, B]);
    assert.equal(await h.used(), 1);
    await h.as("postgres");
    const row = (await db.query<{ chapter_mode: string; chapter_keys: string[]; requested_ruleset: number }>("select chapter_mode,chapter_keys,requested_ruleset from raid_card_battles where run_id=$1", [run])).rows[0];
    assert.deepEqual(row, { chapter_mode: "manual", chapter_keys: row.chapter_keys, requested_ruleset: 4 });
    assert.deepEqual([...row.chapter_keys].sort(), [A, B].sort());

    // Mode and keys are stored together or not at all.
    await assert.rejects(db.query("update raid_card_battles set chapter_keys=null where run_id=$1", [run]), /chapter_keys_check/);
    await assert.rejects(db.query("update raid_card_battles set chapter_mode=null where run_id=$1", [run]), /chapter_keys_check/);

    // An unfinished run is returned as it is, without another key.
    assert.equal(await h.startArena("manual", [C]), run);
    assert.equal(await h.used(), 1);
    await h.closeRuns();

    for (const [mode, keys, message] of [
      ["manual", [key("math", "Small")], /ไม่พอ/],
      ["manual", ["nope"], /ไม่พอ/],
      ["manual", [], /1–3/],
      ["manual", null, /1–3/],
      ["manual", [A, B, C, D], /1–3/],
      ["weird", [A], /Invalid chapter mode/],
      [null, [A], /Invalid chapter mode/],
    ] as const) {
      await assert.rejects(h.startArena(mode, keys as string[] | null), message);
      assert.equal(await h.used(), 1, `no key used for ${mode} ${JSON.stringify(keys)}`);
    }

    const auto = await h.startArena("auto", null);
    await h.as("postgres");
    const autoRow = (await db.query<{ chapter_mode: string; chapter_keys: string[] }>("select chapter_mode,chapter_keys from raid_card_battles where run_id=$1", [auto])).rows[0];
    assert.equal(autoRow.chapter_mode, "auto");
    assert.equal(autoRow.chapter_keys.length, 3);
    for (const k of autoRow.chapter_keys) assert.ok([A, B, C, D].includes(k));
    await h.closeRuns();

    // The chips shown on the page can be sent back and are the chapters really used.
    const echoed = await h.startArena("auto", [D, C]);
    await h.as("postgres");
    const echoedKeys = (await db.query<{ chapter_keys: string[] }>("select chapter_keys from raid_card_battles where run_id=$1", [echoed])).rows[0].chapter_keys;
    assert.deepEqual([...echoedKeys].sort(), [C, D].sort());
  } finally { await db.close(); }
});

test("arena: pick_raid_move draws from chosen chapters and repeats safely", async () => {
  const db = await setup();
  const h = helpers(db);
  try {
    const run = await h.startArena("manual", [A, B]);
    await h.initState(run);
    await h.pick(run, 1, "counter");
    const [first] = await h.picked(run, 1);
    assert.equal(first.card_id, "counter");
    assert.ok(["A", "B"].includes(first.category));
    assert.equal(first.subject, "math");

    await h.pick(run, 1, "mend");
    assert.deepEqual(await h.picked(run, 1), [first], "same revision never redraws");
    await h.pick(run, 99);
    assert.deepEqual(await h.picked(run, 99), [], "old revision does nothing");

    let revision = await h.bump(run);
    await assert.rejects(h.pick(run, revision, "guard"), /Invalid move/);
    await assert.rejects(h.pick(run, revision, null as unknown as string), /Invalid move/);

    // Chapters stay within one question of each other, with no repeats.
    const counts: Record<string, number> = { A: 0, B: 0, [first.category]: 1 };
    const seen = new Set([first.question_id]);
    for (let i = 0; i < 7; i++) {
      await h.pick(run, revision);
      const [row] = await h.picked(run, revision);
      counts[row.category]++;
      assert.ok(!seen.has(row.question_id), "no repeated question");
      seen.add(row.question_id);
      assert.ok(Math.abs(counts.A - counts.B) <= 1, JSON.stringify(counts));
      revision = await h.bump(run);
    }

    await h.as("postgres");
    await db.query("update raid_card_battles set finished_at=now() where run_id=$1", [run]);
    await h.pick(run, revision);
    assert.deepEqual(await h.picked(run, revision), [], "finished battle returns quietly");
    await h.closeRuns();
    await assert.rejects(h.pick(run, revision), /ไม่พบรอบ/, "a claimed run is no longer active");

    // Version 3 rounds keep their own route.
    await h.as("authenticated");
    const v3 = (await h.scalar("select start_raid_card_run($1,$2) as value", [pet, mist]))!;
    await h.as("service_role");
    const stats = (await db.query<{ stat_snapshot: Stats }>("select stat_snapshot from raid_runs where id=$1", [v3])).rows[0].stat_snapshot;
    await db.query("select commit_raid_card_turn($1,$2,0,$3)", [v3, user, JSON.stringify(createBattle("ridge_mist", stats, () => 0.4))]);
    await assert.rejects(h.pick(v3, 1), /Invalid ruleset/);
    await h.closeRuns();

    // Running v4 rounds have no chapter columns and draw from the whole band.
    await h.as("authenticated");
    const legacy = (await h.scalar("select start_raid_chapter_run($1,$2) as value", [pet, mist]))!;
    await h.initState(legacy);
    await h.as("postgres");
    assert.equal(await h.scalar("select (chapter_mode is null and chapter_keys is null)::text as value from raid_card_battles where run_id=$1", [legacy]), "true");
    await h.pick(legacy, 1);
    const [any] = await h.picked(legacy, 1);
    assert.ok(any && any.category !== "Senior");
  } finally { await db.close(); }
});

test("arena: exhausted chapters widen to the band, then the round can finish", async () => {
  const db = await setup();
  const h = helpers(db);
  try {
    const run = await h.startArena("manual", [C]);
    await h.initState(run);
    await h.as("postgres");
    // Leave 1 question in the chosen chapter and 1 in another chapter of the band.
    await db.exec(`
      update questions set status='inactive' where grade_band='junior' and id not in
        ((select min(id) from questions where chapter='C'),(select min(id) from questions where chapter='D'));
    `);
    let revision = 1;
    await h.pick(run, revision);
    assert.equal((await h.picked(run, revision))[0].category, "C");
    revision = await h.bump(run);
    await h.pick(run, revision);
    assert.equal((await h.picked(run, revision))[0].category, "D", "chosen chapter empty, widen to band");
    revision = await h.bump(run);
    await assert.rejects(h.pick(run, revision), /RAID_NO_QUESTIONS/);
    assert.deepEqual(await h.picked(run, revision), []);

    await h.as("service_role");
    await db.query("select finish_exhausted_raid_chapters($1,$2,$3)", [run, user, revision]);
    await h.as("postgres");
    assert.equal(await h.scalar("select phase as value from raid_runs where id=$1", [run]), "card_reward");
    assert.equal(await h.scalar("select state->>'defeatReason' as value from raid_card_battles where run_id=$1", [run]), "content");
  } finally { await db.close(); }
});

test("arena: picked move answers through the existing RPC", async () => {
  const db = await setup();
  const h = helpers(db);
  try {
    const run = await h.startArena("manual", [A]);
    const state: Battle = await h.initState(run);
    await h.pick(run, 1, "mend");
    const next = resolveTurn(state, "mend", () => 0.4, true);
    await h.as("service_role");
    await assert.rejects(db.query("select answer_raid_card_question($1,$2,1,0,$3)", [run, user, JSON.stringify(resolveTurn(state, "strike", () => 0.4, true))]), /mismatch/);
    const result = await db.query<{ value: { revision: number } }>("select answer_raid_card_question($1,$2,1,0,$3) as value", [run, user, JSON.stringify(next)]);
    assert.equal(result.rows[0].value.revision, 2);
    await h.as("postgres");
    assert.equal(await h.scalar("select source as value from quiz_attempts where raid_run_id=$1", [run]), "raid_boss");
    assert.equal(await h.scalar("select answer_index::text as value from raid_card_questions where run_id=$1 and revision=1", [run]), "0");
    await h.pick(run, 2, "strike");
    assert.equal((await h.picked(run, 2))[0].card_id, "strike");
  } finally { await db.close(); }
});

